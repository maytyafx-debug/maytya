def env(name, default=""):
    return (os.getenv(name) or default).strip()


def normalize(value):
    value = str(value or "").strip()
    value = value.replace("ي", "ی").replace("ك", "ک")
    return re.sub(r"[\s‌ـ]+", "", value)


def read_json(path):
    if not path.exists():
        return {}

    with path.open("r", encoding="utf-8") as file:
        return json.load(file)


def all_recent_titles():
    data = read_json(HISTORY_FILE)
    result = set()

    for section in data.get("sections", {}).values():
        if not isinstance(section, dict):
            continue

        for item in section.get("items", []):
            if isinstance(item, dict) and item.get("title"):
                result.add(normalize(item["title"]))

    return result


def get_headlines(key):
    result = []

    for url in FEEDS.get(key, []):
        try:
            response = requests.get(
                url,
                timeout=12,
                headers={"User-Agent": "Mozilla/5.0 Metatya"}
            )
            response.raise_for_status()
            root = ET.fromstring(response.content)

            for item in root.iter("item"):
                title = (item.findtext("title") or "").strip()

                if title:
                    result.append(title)

                if len(result) >= 15:
                    break

        except Exception as exc:
            print(f"RSS warning [{key}]: {str(exc)[:100]}")

    return result[:15]


def fa_ratio(text):
    letters = [char for char in text if char.isalpha()]

    if not letters:
        return 0

    return sum(
        "\u0600" <= char <= "\u06ff"
        for char in letters
    ) / len(letters)


def validate_items(items, tabs, key):
    if not isinstance(items, list):
        raise ValueError("items باید آرایه باشد")

    tab_lookup = {normalize(tab): tab for tab in tabs}
    counts = {tab: 0 for tab in tabs}
    clean = []

    for item in items:
        if not isinstance(item, dict):
            continue

        tab = tab_lookup.get(normalize(item.get("tab")))
        title = str(item.get("title") or "").strip()
        body = str(item.get("body") or "").strip()
        script = item.get("short_script")

        if tab is None:
            continue

        if not 5 <= len(title) <= 140:
            continue

        if not 60 <= len(body) <= 900:
            continue

        if fa_ratio(title + body) < 0.55:
            continue

        if any(word in title + body for word in BANNED):
            continue

        if not isinstance(script, list) or len(script) != 3:
            continue

        if not all(
            isinstance(sentence, str)
            and 3 <= len(sentence.strip()) <= 120
            for sentence in script
        ):
            continue

        disclaimer = DISCLAIMER.get(
            KIND.get(key, "general"),
            ""
        )

        if disclaimer and disclaimer not in body:
            body += " " + disclaimer

        clean.append({
            "tab": tab,
            "title": title,
            "body": body,
            "short_script": script
        })

        counts[tab] += 1

    missing = [
        tab for tab, count in counts.items()
        if count == 0
    ]

    duplicate = [
        tab for tab, count in counts.items()
        if count > 1
    ]

    if missing or duplicate:
        raise ValueError(
            f"پوشش تب ناقص است؛ جاافتاده={missing} تکراری={duplicate}"
        )

    return clean


def local_fallback(key, tabs, recent):
    bank = LOCAL_BANK.get(key)

    if not bank:
        raise RuntimeError(
            f"fallback محلی برای حوزه {key} آماده نیست"
        )

    output = []

    for tab in tabs:
        candidates = bank.get(tab, [])

        selected = next(
            (
                entry for entry in candidates
                if normalize(entry[0]) not in recent
            ),
            None
        )

        if not selected:
            raise RuntimeError(
                f"بانک موضوعات {key}/{tab} تمام شده است؛ "
                "موضوع تکراری تولید نشد."
            )

        title, explanation = selected

        short_explanation = re.split(
            r"(?<=[.!؟])\s+",
            explanation.strip(),
            maxsplit=1
        )[0].strip()

        if len(short_explanation) > 120:
            short_explanation = (
                short_explanation[:117].rstrip(" ،؛:")
                + "..."
            )

        body = (
            f"{title}. {explanation} "
            "برای تمرین این موضوع، یک نمونه تاریخی یا مستند را انتخاب کن، "
            "مشاهدات خود را بنویس و میان داده، فرضیه و نتیجه‌گیری تفاوت بگذار. "
            "در ارزیابی این موضوع، محدودیت اطلاعات و احتمال خطا را نیز در نظر بگیر."
        )

        output.append({
            "tab": tab,
            "title": title,
            "body": body,
            "short_script": [
                title,
                short_explanation,
                "این نکته را با منبع معتبر بررسی و برای مرور ثبت کن."
            ]
        })

        recent.add(normalize(title))

    return validate_items(output, tabs, key)


def call_openrouter(prompt):
    api_key = env("OPENROUTER_API_KEY")

    if not api_key:
        raise RuntimeError("کلید OpenRouter تنظیم نشده است")

    models = [
        model.strip()
        for model in env(
            "OR_MODELS",
            OR_MODELS_DEFAULT
        ).split(",")
        if model.strip()
    ]

    if not models:
        raise RuntimeError("فهرست مدل‌ها خالی است")

    last_error = "unknown"

    for model in models:
        payload = {
            "model": model,
            "temperature": 0.35,
            "max_tokens": 5000,
            "response_format": {"type": "json_object"},
            "messages": [
                {
                    "role": "system",
                    "content": "Return valid JSON only."
                },
                {
                    "role": "user",
                    "content": prompt
                }
            ]
        }

        headers = {
            "Authorization": f"Bearer {api_key}",
            "Content-Type": "application/json",
            "HTTP-Referer": "https://maytyafx-debug.github.io/maytya/",
            "X-Title": "Metatya"
        }

        try:
            response = requests.post(
                OR_URL,
                headers=headers,
                json=payload,
                timeout=60
            )

            if response.status_code == 429:
                retry = response.headers.get("Retry-After", "5")

                try:
                    wait = min(max(int(float(retry)), 1), 10)
                except ValueError:
                    wait = 5

                time.sleep(wait)

                response = requests.post(
                    OR_URL,
                    headers=headers,
                    json=payload,
                    timeout=60
                )

            if response.status_code in (401, 403):
                raise RuntimeError(
                    "کلید OpenRouter معتبر نیست یا دسترسی ندارد"
                )

            response.raise_for_status()

            content = (
                response.json()["choices"][0]["message"].get("content")
            )

            if not content:
                raise ValueError("مدل پاسخ خالی برگرداند")

            match = re.search(r"\{.*\}", content, re.S)

            if not match:
                raise ValueError("JSON در پاسخ مدل پیدا نشد")

            return json.loads(match.group(0)), model

        except Exception as exc:
            last_error = f"{model}: {str(exc)[:160]}"
            print("OpenRouter fallback:", last_error)

    raise RuntimeError(last_error)


def generate_section(key, name, tabs, recent):
    context = get_headlines(key)

    context_text = "\n".join(
        "- " + headline for headline in context
    ) or "خبر قابل اتکا در دسترس نیست؛ فقط آموزش ماندگار بنویس."

    history_text = "\n".join(sorted(recent))[-12000:] or "ندارد"

    prompt = PROMPT.format(
        name=name,
        today=datetime.date.today().isoformat(),
        tabs="، ".join(tabs),
        context=context_text,
        history=history_text
    )

    if env("OPENROUTER_API_KEY"):
        try:
            payload, model = call_openrouter(prompt)
            items = validate_items(
                payload.get("items"),
                tabs,
                key
            )

            for item in items:
                if normalize(item["title"]) in recent:
                    raise ValueError("عنوان تکراری با محتوای اخیر")

            return items, model

        except Exception as exc:
            print(
                f"AI failed [{key}], using local fallback: {exc}"
            )

    items = local_fallback(key, tabs, recent)

    return items, "local-fallback"


def main():
    # OUT ممکن است فایل موقت و خالی باشد.
    # تاریخچه باید از HISTORY_FILE خوانده شود، نه از OUT.
    old_data = read_json(OUT)
    old_sections = old_data.get("sections", {})

    history_data = read_json(HISTORY_FILE)
    recent = set()

    for section in history_data.get("sections", {}).values():
        if not isinstance(section, dict):
            continue

        for item in section.get("items", []):
            if isinstance(item, dict) and item.get("title"):
                recent.add(normalize(item["title"]))

    now = datetime.datetime.now(datetime.timezone.utc)
    today = now.date().isoformat()

    result = {}
    successes = 0

    for key, (name, tabs, _needs_web) in SECTIONS.items():
        previous_section = old_sections.get(key, {})

        previous = (
            previous_section.get("items", [])
            if isinstance(previous_section, dict)
            else []
        )

        section_recent = set(recent)

        try:
            items, provider = generate_section(
                key,
                name,
                tabs,
                section_recent
            )

            for item in items:
                item["date"] = today
                item["provider"] = provider
                recent.add(normalize(item["title"]))

            result[key] = {
                "name": name,
                "items": (items + previous)[:KEEP],
                "ok": True,
                "provider": provider
            }

            successes += 1

            print(
                f"OK {key}: {len(items)} items [{provider}]"
            )

        except Exception as exc:
            result[key] = {
                "name": name,
                "items": previous[:KEEP],
                "ok": False,
                "provider": None,
                "error": str(exc)[:300]
            }

            print(f"FAIL {key}: {exc}")

    OUT.parent.mkdir(parents=True, exist_ok=True)

    output = {
        "updated": now.isoformat(timespec="seconds"),
        "note": (
            "محتوای آموزشی عمومی؛ اطلاعات بازار لحظه‌ای نیست و "
            "مطالب جایگزین مشاوره تخصصی نیستند."
        ),
        "sections": result
    }

    with OUT.open("w", encoding="utf-8") as file:
        json.dump(
            output,
            file,
            ensure_ascii=False,
            indent=2
        )

    print(
        f"RESULT: {successes}/{len(SECTIONS)} sections succeeded"
    )

    if successes == 0:
        sys.exit(1)


if __name__ == "__main__":
    main()
